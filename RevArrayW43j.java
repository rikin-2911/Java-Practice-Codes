public class RevArrayW43j {
    public static void main(String [] args){
        int arr[] = {22, 33, 88, 66, 54, 11, 847};
        int n = arr.length - 1;
        System.out.print("The reversed array is: " );
        for(int i = n; i > 0; i--){
            System.out.print(arr[i] + "  ");    
        }
    }
}
